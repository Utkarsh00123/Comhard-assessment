/**
 * ============================================================================
 * TYPE DEFINITIONS & DATA CONTRACTS
 * ============================================================================
 * This file serves as the single source of truth for all core data structures
 * used throughout both the frontend UI and the backend API routes.
 * 
 * Having unified types ensures strict type safety, prevents runtime shape
 * mismatches, and guarantees consistency between database records and React state.
 */

/**
 * TaskStatus
 * ----------------------------------------------------------------------------
 * HOW IT WORKS:
 * Represents the three discrete stages of a task's lifecycle.
 * - 'To Do': Task is pending and waiting for action.
 * - 'In Progress': Work is actively being performed on the task.
 * - 'Done': Task is completed.
 * 
 * WHERE ITS EFFECTS LEAD:
 * - Controls which column a task appears in on the Kanban board.
 * - Dictates SLA tracking behavior (e.g. active time counts in To Do & In Progress,
 *   but automatically halts and zeroes out once in 'Done').
 * - Validated strictly in API routes (/api/tasks and /api/tasks/[id]).
 */
export type TaskStatus = 'To Do' | 'In Progress' | 'Done'

/**
 * TaskImportance
 * ----------------------------------------------------------------------------
 * HOW IT WORKS:
 * Defines the priority level assigned to a task.
 * 
 * WHERE ITS EFFECTS LEAD:
 * - Determines visual styling (pill colors: Red for High, Amber for Medium, Blue for Low).
 * - Used by the Global Filter Bar so users can filter tasks by one or more priorities.
 */
export type TaskImportance = 'High' | 'Medium' | 'Low'

/**
 * User
 * ----------------------------------------------------------------------------
 * HOW IT WORKS:
 * Represents the authenticated user profile in the client-side session.
 * 
 * WHERE ITS EFFECTS LEAD:
 * - Populated into React AuthContext after successful login/signup or session restore.
 * - Displayed in the UI header/sidebar so the user knows who is signed in.
 * - Links tasks in the database via the foreign key `user_id`.
 */
export interface User {
  id: string
  email: string
  name: string
  createdAt?: string
}

/**
 * Task
 * ----------------------------------------------------------------------------
 * HOW IT WORKS:
 * The primary business entity of the application. It captures task metadata
 * along with lifecycle timing attributes required by the SLA Engine.
 * 
 * WHERE ITS EFFECTS LEAD:
 * - Managed in `TaskContext.tsx` as a unified array (`tasks`).
 * - Rendered across all 4 view modes (List, Grid, Kanban, Section).
 * - Stored in PostgreSQL `tasks` table and manipulated via `/api/tasks` endpoints.
 * - Timers (`timeInTodoSeconds`, `timeInProgressSeconds`, `currentStageEnteredAt`)
 *   feed the live real-time SLA calculation engine.
 */
export interface Task {
  /** Unique UUID identifier generated by the database */
  id: string
  /** Foreign key pointing to the user who owns this task */
  user_id: string
  /** Short headline summary of the task */
  title: string
  /** Detailed markdown or text notes for the task */
  description: string
  /** User-defined category label (e.g., 'Engineering', 'Design', 'Marketing') */
  category: string
  /** Current workflow phase */
  status: TaskStatus
  /** Priority level */
  importance: TaskImportance
  /** ISO 8601 date string indicating task deadline */
  dueDate: string
  /** ISO 8601 timestamp when the task was initially inserted into the database */
  createdAt: string
  /** ISO 8601 timestamp tracking when the task entered its current status */
  currentStageEnteredAt: string
  /** Cumulative historical seconds spent in 'To Do' across all transitions */
  timeInTodoSeconds: number
  /** Cumulative historical seconds spent in 'In Progress' across all transitions */
  timeInProgressSeconds: number
  /** Number of times the task has moved between different statuses */
  stageTransitionsCount: number
}

/**
 * TaskFilterState
 * ----------------------------------------------------------------------------
 * HOW IT WORKS:
 * Holds the active filtering and sorting parameters selected by the user.
 * 
 * WHERE ITS EFFECTS LEAD:
 * - Stored in `TaskContext`.
 * - Fed into a `useMemo` computation to derive `filteredTasks`.
 * - Every view (List, Grid, Kanban, Section) dynamically reflects these filter
 *   rules in real time without mutating the original tasks array.
 */
export interface TaskFilterState {
  /** Multi-select array of priorities to show (empty array means show all) */
  importance: TaskImportance[]
  /** Sorting mode for task display */
  dateSort: 'due_date_asc' | 'due_date_desc' | 'created_at_desc' | 'created_at_asc'
  /** Filter by category, or 'all' to show all categories */
  category: string
  /** Substring search query matched case-insensitively against title and description */
  searchQuery: string
}

/**
 * SLAMetrics
 * ----------------------------------------------------------------------------
 * HOW IT WORKS:
 * Calculated metrics measuring adherence to Service Level Agreements (SLA).
 * 
 * WHERE ITS EFFECTS LEAD:
 * - Displayed on individual task cards to show live seconds spent in current stage.
 * - Displayed on the top SLA dashboard metrics bar for cumulative portfolio health.
 * - Updates every 1000ms using a live tick in `TaskContext`.
 */
export interface SLAMetrics {
  /** Seconds elapsed in the active stage (0 if task is 'Done') */
  timeInCurrentSectionSeconds: number
  /** Total cumulative active seconds spent before reaching 'Done' */
  totalCumulativeTimeSeconds: number
  /** Average seconds spent per stage transition (totalCumulative / transitions) */
  averageSLAPerTransitionSeconds: number
}

